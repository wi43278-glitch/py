'''

문 : 사용자로부터 전화번호 입력 받아 (010-2345-3456)
    하이픈을 제거하고
    오직 숫자로만 구성되어 있는지 확인하기
    숫자중 '0'의 개수 갯수 세기







'''


phone = '010-2345-3456'
st2 = phone.replace('-', '')              # 하이픈 제거
print('하이픈 제거:', st2)
print('숫자로만 구성?:', st2.isdigit())   # 제거한 문자열로 검사
print("'0'의 개수:", st2.count('0'))      # 0의 개수 세기


