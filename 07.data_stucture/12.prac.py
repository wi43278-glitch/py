'''
편의점에서 주말 (토요일 , 일요일) 알바의 근무시간을 저장한 튜플
            토요일 오전, 토요일 오후, 일요일 오전, 일요일 오후 근무 시간
        work_hours = (4,5,3,4)
        문1. 주말동안 일 한 총   근무 시간의 합 구하기 
        문2. 일요일 근무 시간만 따로 떼어내어 sun_hours 라는 새로운 튜플을 만들어 출력
        문3. 토요일 오전 근무 시간이 4시간에서 5시간으로 변경

'''

# 토요일 오전, 토요일 오후, 일요일 오전, 일요일 오후 근무 시간
work_hours = (4, 5, 3, 4)

# 문1. 주말 총 근무 시간
total = sum(work_hours)
print('총 근무 시간 =', total)

# 문2. 일요일 근무 시간만 새 튜플로
sun_hours = work_hours[2:]
print('일요일 근무 시간 =', sun_hours)

# 문3. 토요일 오전 근무 시간을 4 -> 5로 변경
# work_hours[0] = 5   # TypeError: 튜플은 항목 대입이 안 됨
work_hours = (5,) + work_hours[1:]
print('변경 후 =', work_hours)


